import type { Episode, Podcast } from '@podcast/types';

export function formatDate(iso: string | null | undefined, lang = 'en', style: 'long' | 'short' | 'numeric' = 'long'): string {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  const opts: Intl.DateTimeFormatOptions =
    style === 'numeric' ? { year: 'numeric', month: '2-digit', day: '2-digit' }
      : style === 'short' ? { month: 'short', day: 'numeric' }
        : { year: 'numeric', month: 'long', day: 'numeric' };
  try {
    return new Intl.DateTimeFormat(lang, { ...opts, timeZone: 'UTC' }).format(d);
  } catch {
    return d.toISOString().slice(0, 10);
  }
}

/** "1 hr 5 min", "42 min", "45 sec". */
export function formatDuration(sec: number): string {
  if (!sec || sec < 0) return '';
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  if (h > 0) return `${h} hr${m ? ` ${m} min` : ''}`;
  if (m > 0) return `${m} min`;
  return `${Math.round(sec)} sec`;
}

/** ISO-8601 duration for structured data (PT1H5M3S). */
export function isoDuration(sec: number): string {
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = Math.floor(sec % 60);
  return `PT${h ? `${h}H` : ''}${m ? `${m}M` : ''}${s || (!h && !m) ? `${s}S` : ''}`;
}

/** "S2 · E14", "Trailer", "Bonus". */
export function episodeLabel(e: Pick<Episode, 'episode_number' | 'season_number' | 'episode_type'>): string {
  if (e.episode_type === 'trailer') return 'Trailer';
  const parts: string[] = [];
  if (e.season_number) parts.push(`S${e.season_number}`);
  if (e.episode_number) parts.push(`E${e.episode_number}`);
  const label = parts.join(' · ');
  if (e.episode_type === 'bonus') return label ? `Bonus · ${label}` : 'Bonus';
  return label;
}

export const podcastHref = (p: Pick<Podcast, 'slug'> | string) => `/podcast/${typeof p === 'string' ? p : p.slug}`;
export const episodeHref = (e: Pick<Episode, 'podcast_slug' | 'slug'>) => `/podcast/${e.podcast_slug}/${e.slug}`;
export const categoryHref = (slug: string) => `/category/${slug}`;
export const hostHref = (slug: string) => `/host/${slug}`;
export const tagHref = (name: string) => `/tag/${slugify(name)}`;
export const collectionHref = (slug: string) => `/collection/${slug}`;

export function slugify(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80) || 'item';
}

export function initials(name: string): string {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0]!.toUpperCase())
    .join('');
}

/** Picks the WebP variant URL generated by the image pipeline when it exists ( -medium.webp ). */
export function imageVariant(url: string | undefined | null, _size: 'thumbnail' | 'small' | 'medium' | 'large' = 'medium'): string {
  return url || '';
}

export function plural(n: number, one: string, many = one + 's'): string {
  return `${n.toLocaleString('en')} ${n === 1 ? one : many}`;
}
