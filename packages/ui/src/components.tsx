/** Square artwork with alt text and a graceful fallback (PRD §82 image alt text). */
export function Artwork({
  src, alt, size, className, priority, rounded, srcSet, sizes,
}: {
  src?: string | null; alt: string; size?: number; className?: string; priority?: boolean; rounded?: boolean;
  srcSet?: string; sizes?: string;
}) {
  const style: CSSProperties = size ? { width: size, height: size } : {};
  // Responsive WebP variants generated by the image pipeline, when available.
  const autoSet = srcSet ?? variantSrcSet(src);
  const autoSizes = sizes ?? (size ? `${size}px` : '(max-width: 700px) 90vw, 420px');
  if (!src) {
    return (
      <div className={`pe-art pe-art--fallback ${className ?? ''}`} style={style} role="img" aria-label={alt}>
        <span aria-hidden="true">{initials(alt)}</span>
      </div>
    );
  }
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      className={`pe-art ${rounded ? 'pe-art--round' : ''} ${className ?? ''}`}
      src={src}
      srcSet={autoSet}
      sizes={autoSet ? autoSizes : undefined}
      alt={alt}
      width={size ?? 600}
      height={size ?? 600}
      loading={priority ? 'eager' : 'lazy'}
      fetchPriority={priority ? 'high' : undefined}
      decoding="async"
      style={style}
    />
  );
}

/** Sanitized HTML from the API (sanitized server-side with bluemonday, PRD §77). */
export function Prose({ html, className }: { html?: string | null; className?: string }) {
  if (!html) return null;
  return <div className={`pe-prose ${className ?? ''}`} dangerouslySetInnerHTML={{ __html: html }} />;
}

/** JSON-LD structured data block (PRD §35). */
export function JsonLd({ data }: { data: unknown }) {
  const json = JSON.stringify(data).replace(/</g, '\\u003c');
  return <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: json }} />;
}

